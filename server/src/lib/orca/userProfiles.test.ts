import { describe, expect, it } from "vitest";
import { orcaValue, parseOrcaFilament } from "./userProfiles";

// Shapes copied from real files in ~/Library/Application Support/OrcaSlicer/user/default/filament.
const walnut = {
  _comment: "Generated by spoolman2slicer v0.10.0",
  default_filament_colour: ["#564e44"],
  filament_cost: ["17.0"],
  filament_spool_weight: ["130.0"],
  filament_type: ["PLA"],
  filament_diameter: ["1.75"],
  filament_density: ["1.25"],
  filament_flow_ratio: ["0.94"],
  filament_vendor: ["Sunlu"],
  from: "User",
  inherits: "Voron Generic PLA",
  name: "Walnut Wood",
  nozzle_temperature: ["210"],
  hot_plate_temp: ["60"],
};

describe("OrcaSlicer user profile import", () => {
  it("reads single-element arrays and treats nil as unset", () => {
    expect(orcaValue(["210"])).toBe("210");
    expect(orcaValue(["nil"])).toBeNull();
    expect(orcaValue(undefined)).toBeNull();
  });

  it("parses a spoolman2slicer profile and flags its template values", () => {
    const row = parseOrcaFilament("Sunlu - Walnut Wood.json", walnut);
    expect(row).toMatchObject({
      vendor: "Sunlu",
      material: "PLA",
      line: "Wood",
      colorName: "Walnut",
      colorHex: "#564E44",
      density: 1.25,
      spoolWeightG: 130,
      costPerKg: 17,
      generatedBy: "spoolman2slicer",
    });
    expect(row.settings).toMatchObject({ nozzle_temperature: "210", filament_flow_ratio: "0.94", hot_plate_temp: "60" });
    expect(row.warnings.join(" ")).toMatch(/template default/);
    expect(row.warnings.join(" ")).toMatch(/Voron/);
  });

  it("infers vendor, material and color from a hand-made profile name", () => {
    const row = parseOrcaFilament("COMGROW PLA Red.json", {
      name: "COMGROW PLA Red",
      inherits: "Creality Generic ABS",
      filament_vendor: ["Comgrow"],
      filament_type: ["PLA"],
      default_filament_colour: ["#FB0207"],
    });
    expect(row).toMatchObject({ vendor: "Comgrow", material: "PLA", colorName: "Red" });
    expect(row.warnings.join(" ")).toMatch(/different material/);
  });

  it("falls back to inherits for material and drops profile noise words", () => {
    const row = parseOrcaFilament("Deeplee PLA 1.75mm.json", { name: "Deeplee PLA 1.75mm", inherits: "Creality Generic PLA", filament_vendor: ["DeepLee"] });
    expect(row).toMatchObject({ vendor: "DeepLee", material: "PLA", colorName: null });
    const copy = parseOrcaFilament("SUNLU PETG @System - Copy.json", { name: "SUNLU PETG @System - Copy", inherits: "SUNLU PETG @System" });
    expect(copy).toMatchObject({ vendor: "SUNLU", material: "PETG", colorName: null });
  });
});
