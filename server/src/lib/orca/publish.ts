// Writes Spoolkeeper's presets straight into OrcaSlicer's user filament
// folder, without ever losing anything:
//  - a file is only touched if its filament_notes carry our ownership tag;
//    a same-named preset someone else made blocks the publish instead
//  - the file is merged, not replaced: keys we don't set (anything
//    OrcaSlicer or you added) stay as they are
//  - every value we wrote is remembered; if one has since changed in the
//    file it was edited in OrcaSlicer ("hand-tuned") and is kept unless
//    you choose to overwrite it
//  - whatever is replaced or removed is copied to data/backups/ first
//  - identical content is never rewritten

const TAG_RE = /spoolkeeper:((?:spool=\d+;)?product=\d+)/;
const LEGACY_MARK = "Generated by spoolman2slicer";

export const filamentDir = () => path.join(config.orcaUserDir, "filament");

export interface OrcaFile {
  /** "Sunlu PLA Wood Walnut (Spool #13).json" - top-level files only. */
  fileName: string;
  json: Record<string, unknown>;
  text: string;
  /** Our tag ("spool=13;product=7") when Spoolkeeper made it. */
  owner: string | null;
}

/** Every user filament preset in OrcaSlicer's folder (subfolders like base/ are OrcaSlicer's own). */
export function readUserFilaments(dir = filamentDir()): OrcaFile[] {
  let names: string[];
  try {
    names = fs.readdirSync(dir).filter((n) => n.endsWith(".json"));
  } catch {
    return [];
  }
  const files: OrcaFile[] = [];
  for (const fileName of names.sort()) {
    try {
      const text = fs.readFileSync(path.join(dir, fileName), "utf8");
      const json = JSON.parse(text) as Record<string, unknown>;
      const notes = flat(json.filament_notes) ?? "";
      files.push({ fileName, json, text, owner: TAG_RE.exec(notes)?.[1] ?? null });
    } catch {
      // Not a preset we can read - leave it alone.
    }
  }
  return files;
}

/** OrcaSlicer stores most values as one-element string arrays; this is the comparable/displayable form. */
function flat(v: unknown): string | null {
  if (v === undefined || v === null) return null;
  if (Array.isArray(v)) return v.map(String).join(", ");
  return String(v);
}
const same = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b);

export function folderWritable(dir = filamentDir()): { ok: boolean; reason?: string } {
  try {
    fs.accessSync(dir, fs.constants.W_OK);
    // A read-only bind mount can still pass access(); a real write settles it.
    const probe = path.join(dir, `.spoolkeeper-write-test-${process.pid}`);
    fs.writeFileSync(probe, "");
    fs.unlinkSync(probe);
    return { ok: true };
  } catch (e) {
    const code = (e as NodeJS.ErrnoException).code;
    return {
      ok: false,
      reason:
        code === "ENOENT"
          ? `OrcaSlicer's filament folder wasn't found at ${dir}.`
          : code === "EROFS" || code === "EACCES" || code === "EPERM"
            ? "OrcaSlicer's folder is mounted read-only. Remove :ro from the OrcaSlicer volume in docker-compose.yml and restart the container."
            : `Can't write to ${dir}: ${(e as Error).message}`,
    };
  }
}

// ---- Records of what was published -----------------------------------------

export interface PublishedRecord {
  owner: string;
  scope: "spool" | "product";
  spoolId: number | null;
  productId: number;
  fileName: string;
  written: Record<string, unknown>;
  contentHash: string;
  backupDir: string | null;
  publishedAt: string;
}

function toRecord(r: Record<string, unknown>): PublishedRecord {
  return {
    owner: r.owner as string,
    scope: r.scope as "spool" | "product",
    spoolId: (r.spool_id as number | null) ?? null,
    productId: r.product_id as number,
    fileName: r.file_name as string,
    written: JSON.parse(r.written as string) as Record<string, unknown>,
    contentHash: r.content_hash as string,
    backupDir: (r.backup_dir as string | null) ?? null,
    publishedAt: r.published_at as string,
  };
}

export function listPublished(): PublishedRecord[] {
  return (getDb().prepare("SELECT * FROM published_profiles").all() as Record<string, unknown>[]).map(toRecord);
}

function getPublished(owner: string): PublishedRecord | null {
  const r = getDb().prepare("SELECT * FROM published_profiles WHERE owner = ?").get(owner) as Record<string, unknown> | undefined;
  return r ? toRecord(r) : null;
}

function savePublished(rec: Omit<PublishedRecord, "publishedAt">) {
  getDb()
    .prepare(
      `INSERT INTO published_profiles (owner, scope, spool_id, product_id, file_name, written, content_hash, backup_dir)
       VALUES (@owner, @scope, @spoolId, @productId, @fileName, @written, @contentHash, @backupDir)
       ON CONFLICT(owner) DO UPDATE SET scope = excluded.scope, spool_id = excluded.spool_id, product_id = excluded.product_id,
         file_name = excluded.file_name, written = excluded.written, content_hash = excluded.content_hash,
         backup_dir = COALESCE(excluded.backup_dir, published_profiles.backup_dir),
         published_at = strftime('%Y-%m-%dT%H:%M:%SZ', 'now')`,
    )
    .run({ ...rec, written: JSON.stringify(rec.written) });
}

// ---- Planning ----------------------------------------------------------------

export interface KeyChange {
  key: string;
  /** What OrcaSlicer's file has now (null = not set there). */
  current: string | null;
  /** null = Spoolkeeper no longer sets it: removed, so the inherited base profile's value applies. */
  proposed: string | null;
  /**
   * The file's value isn't what Spoolkeeper last wrote - it was changed in
   * OrcaSlicer. Kept unless the publish asks to overwrite this key.
   */
  handTuned: boolean;
  /** What Spoolkeeper wrote last time, for hand-tuned keys. */
  lastWritten?: string | null;
}

export type PlanState = "new" | "changes" | "current" | "blocked";

export interface PublishPlan {
  owner: string;
  scope: "spool" | "product";
  spoolId: number | null;
  productId: number;
  name: string;
  fileName: string;
  /** The file holding this preset now, if any - differs from fileName after a rename. */
  existingFile: string | null;
  state: PlanState;
  blockedReason?: string;
  changes: KeyChange[];
  publishedAt: string | null;
}

export function planPublish(
  built: BuiltProfile,
  ids: { spoolId: number; productId: number },
  files: OrcaFile[] = readUserFilaments(),
): PublishPlan {
  const owner = TAG_RE.exec(flat(built.json.filament_notes) ?? "")![1];
  const fileName = `${built.fileName}.json`;
  const record = getPublished(owner);
  const mine = files.find((f) => f.owner === owner) ?? null;
  const atTarget = files.find((f) => f.fileName.toLowerCase() === fileName.toLowerCase()) ?? null;
  const base = {
    owner,
    scope: built.scope,
    spoolId: built.scope === "spool" ? ids.spoolId : null,
    productId: ids.productId,
    name: built.name,
    fileName,
    existingFile: mine?.fileName ?? null,
    publishedAt: record?.publishedAt ?? null,
  };

  if (atTarget && atTarget !== mine) {
    return {
      ...base,
      state: "blocked",
      blockedReason: atTarget.owner
        ? `"${atTarget.fileName}" belongs to a different Spoolkeeper ${atTarget.owner.startsWith("spool=") ? "spool" : "product"} (${atTarget.owner}). Rename one of them in Spoolkeeper.`
        : `OrcaSlicer already has a preset named "${built.name}" that Spoolkeeper didn't make. Rename or delete it in OrcaSlicer, then publish again.`,
      changes: [],
    };
  }

  const current = mine?.json ?? {};
  const changes: KeyChange[] = [];
  for (const [key, proposed] of Object.entries(built.json)) {
    if (same(current[key], proposed)) continue;
    const has = key in current;
    // Hand-tuned: we wrote this key before and the file no longer holds what we wrote.
    const wrote = record && mine && key in record.written;
    const handTuned = Boolean(has && wrote && !same(current[key], record!.written[key]));
    changes.push({
      key,
      current: flat(current[key]),
      proposed: flat(proposed) ?? "",
      handTuned,
      ...(handTuned ? { lastWritten: flat(record!.written[key]) } : {}),
    });
  }
  // Keys we wrote last time but no longer set (a calibration run un-accepted,
  // a field cleared): removed - unless they've been changed in OrcaSlicer since.
  if (record && mine)
    for (const [key, was] of Object.entries(record.written)) {
      if (key in built.json || !(key in current)) continue;
      const handTuned = !same(current[key], was);
      changes.push({ key, current: flat(current[key]), proposed: null, handTuned, ...(handTuned ? { lastWritten: flat(was) } : {}) });
    }
  const renamed = mine != null && mine.fileName !== fileName;
  return {
    ...base,
    state: !mine ? "new" : changes.length || renamed ? "changes" : "current",
    changes,
  };
}

// ---- Writing ----------------------------------------------------------------

export interface PublishResult {
  owner: string;
  name: string;
  fileName: string;
  action: "created" | "updated" | "renamed" | "unchanged" | "blocked";
  /** Hand-tuned keys left as OrcaSlicer has them. */
  kept: string[];
  backupDir: string | null;
  error?: string;
}

const stamp = (d = new Date()) => d.toISOString().replace(/[-:]/g, "").replace(/\.\d+Z$/, "Z");
const sha = (s: string) => crypto.createHash("sha256").update(s).digest("hex");

/** Atomic-ish write: OrcaSlicer never sees a half-written preset. */
function writeFile(file: string, text: string) {
  const tmp = `${file}.spoolkeeper-tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, file);
}

function infoPathFor(jsonPath: string) {
  return jsonPath.replace(/\.json$/, ".info");
}

/** Copy a preset (.json + .info) into a backup folder before it's replaced or removed. */
function backup(dir: string, fileName: string, backupDir: string) {
  fs.mkdirSync(backupDir, { recursive: true });
  for (const f of [fileName, fileName.replace(/\.json$/, ".info")]) {
    const src = path.join(dir, f);
    if (fs.existsSync(src)) fs.copyFileSync(src, path.join(backupDir, f));
  }
}

export function newBackupDir(kind: string) {
  return path.join(config.dataDir, "backups", `${kind}-${stamp()}`);
}

export function applyPublish(
  built: BuiltProfile,
  ids: { spoolId: number; productId: number },
  opts: { overwrite?: string[]; backupDir: string; dir?: string },
): PublishResult {
  const dir = opts.dir ?? filamentDir();
  const files = readUserFilaments(dir);
  const plan = planPublish(built, ids, files);
  const result = { owner: plan.owner, name: plan.name, fileName: plan.fileName, kept: [] as string[], backupDir: null as string | null };
  if (plan.state === "blocked") return { ...result, action: "blocked", error: plan.blockedReason };

  const mine = files.find((f) => f.fileName === plan.existingFile) ?? null;
  const record = getPublished(plan.owner);
  const overwrite = new Set(opts.overwrite ?? []);

  // Start from the file as it is, so keys we don't own survive.
  const merged: Record<string, unknown> = { ...(mine?.json ?? {}) };
  const written: Record<string, unknown> = {};
  for (const [key, proposed] of Object.entries(built.json)) {
    const change = plan.changes.find((c) => c.key === key);
    if (change?.handTuned && !overwrite.has(key)) {
      result.kept.push(key);
      // Keep the old baseline, so it still shows as hand-tuned next time.
      written[key] = record!.written[key];
      continue;
    }
    merged[key] = proposed;
    written[key] = proposed;
  }
  for (const c of plan.changes.filter((c) => c.proposed === null)) {
    if (c.handTuned && !overwrite.has(c.key)) {
      result.kept.push(c.key);
      written[c.key] = record!.written[c.key];
    } else delete merged[c.key];
  }
  const sorted = Object.fromEntries(Object.entries(merged).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  const text = profileJsonText({ ...built, json: sorted });
  const target = path.join(dir, plan.fileName);
  const renamed = mine != null && mine.fileName !== plan.fileName;

  if (mine && !renamed && mine.text === text) {
    // Nothing to write; still record it, so a preset exported by download is tracked from now on.
    savePublished({ owner: plan.owner, scope: plan.scope, spoolId: plan.spoolId, productId: plan.productId, fileName: plan.fileName, written, contentHash: sha(text), backupDir: null });
    return { ...result, action: "unchanged" };
  }

  let backupDir: string | null = null;
  if (mine) {
    backup(dir, mine.fileName, opts.backupDir);
    backupDir = opts.backupDir;
  }

  writeFile(target, text);
  // The .info sidecar: keep OrcaSlicer's own when there is one (it tracks
  // sync state), just bumping updated_time; otherwise ours.
  const oldInfoPath = mine ? infoPathFor(path.join(dir, mine.fileName)) : null;
  const oldInfo = oldInfoPath && fs.existsSync(oldInfoPath) ? fs.readFileSync(oldInfoPath, "utf8") : null;
  const now = Math.floor(Date.now() / 1000);
  const info = oldInfo ? oldInfo.replace(/^updated_time = .*$/m, `updated_time = ${now}`) : built.info;
  writeFile(infoPathFor(target), info);

  if (renamed) {
    fs.rmSync(path.join(dir, mine.fileName), { force: true });
    if (oldInfoPath) fs.rmSync(oldInfoPath, { force: true });
  }

  savePublished({ owner: plan.owner, scope: plan.scope, spoolId: plan.spoolId, productId: plan.productId, fileName: plan.fileName, written, contentHash: sha(text), backupDir });
  return { ...result, backupDir, action: !mine ? "created" : renamed ? "renamed" : "updated" };
}

// ---- spoolman2slicer leftovers ------------------------------------------------

export interface LegacyFile {
  fileName: string;
  name: string;
  inherits: string | null;
}

/** Presets spoolman2slicer generated - the ones that kept overwriting tuned settings. */
export function listLegacy(files: OrcaFile[] = readUserFilaments()): LegacyFile[] {
  return files
    .filter((f) => flat(f.json._comment)?.includes(LEGACY_MARK))
    .map((f) => ({ fileName: f.fileName, name: flat(f.json.name) ?? f.fileName.replace(/\.json$/, ""), inherits: flat(f.json.inherits) }));
}

/** Back up, then delete, the chosen spoolman2slicer presets. Anything not generated by it is refused. */
export function removeLegacy(fileNames: string[], backupDir: string, dir = filamentDir()): { removed: string[]; backupDir: string } {
  const legacy = new Set(listLegacy(readUserFilaments(dir)).map((f) => f.fileName));
  const bad = fileNames.filter((f) => !legacy.has(f));
  if (bad.length) throw new HttpError(400, `Not a spoolman2slicer preset: ${bad.join(", ")}`);
  for (const f of fileNames) backup(dir, f, backupDir);
  for (const f of fileNames) {
    fs.rmSync(path.join(dir, f), { force: true });
    fs.rmSync(path.join(dir, f.replace(/\.json$/, ".info")), { force: true });
  }
  return { removed: fileNames, backupDir };
}
