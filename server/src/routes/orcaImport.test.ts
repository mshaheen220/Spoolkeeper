import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import request from "supertest";
import { beforeAll, beforeEach, describe, expect, it } from "vitest";
import type { Express } from "express";

// config reads ORCA_USER_DIR at import time, so point it at a temp folder first.
const orcaDir = fs.mkdtempSync(path.join(os.tmpdir(), "spoolkeeper-orca-"));
fs.mkdirSync(path.join(orcaDir, "filament", "base"), { recursive: true });
const write = (name: string, json: object) => fs.writeFileSync(path.join(orcaDir, "filament", name), JSON.stringify(json));
write("Sunlu - Walnut Wood.json", {
  _comment: "Generated by spoolman2slicer v0.10.0",
  name: "Walnut Wood",
  inherits: "Voron Generic PLA",
  filament_vendor: ["Sunlu"],
  filament_type: ["PLA"],
  default_filament_colour: ["#564e44"],
  filament_cost: ["17.0"],
  filament_flow_ratio: ["0.94"],
  nozzle_temperature: ["210"],
});
write("Comgrow - Red.json", { name: "Red", filament_vendor: ["Comgrow"], filament_type: ["PLA"] });
write("COMGROW PLA Red.json", { name: "COMGROW PLA Red", filament_vendor: ["Comgrow"], filament_type: ["PLA"], nozzle_temperature: ["200"] });
process.env.ORCA_USER_DIR = orcaDir;

let app: Express;
let db: typeof import("../db");
beforeAll(async () => {
  db = await import("../db");
  app = (await import("../app")).createApp();
});
beforeEach(() => db.setDb(db.openDb(":memory:")));

describe("OrcaSlicer import", () => {
  it("previews without writing anything", async () => {
    const res = await request(app).get("/api/import/orca/preview").expect(200);
    expect(res.body.rows.map((r: { fileName: string }) => r.fileName)).toEqual(["Comgrow - Red.json", "COMGROW PLA Red.json", "Sunlu - Walnut Wood.json"]);
    expect((await request(app).get("/api/spools")).body.spools).toHaveLength(0);
  });

  it("imports confirmed rows, merges files of one product, and never imports a file twice", async () => {
    const rows = [
      { fileName: "Sunlu - Walnut Wood.json", vendor: "Sunlu", material: "PLA", line: "Wood", colorName: "Walnut", createSpool: true },
      { fileName: "Comgrow - Red.json", vendor: "Comgrow", material: "PLA", colorName: "Red", createSpool: true },
      { fileName: "COMGROW PLA Red.json", vendor: "Comgrow", material: "PLA", colorName: "Red", createSpool: true },
    ];
    const res = await request(app).post("/api/import/orca").send({ rows }).expect(200);
    expect(res.body).toEqual({ files: 3, productsCreated: 2, productsMatched: 0, spools: 2 });

    const spools = (await request(app).get("/api/spools")).body.spools;
    const walnut = spools.find((s: { product: { displayName: string } }) => s.product.displayName === "Sunlu PLA Wood Walnut");
    expect(walnut.price).toBe(17);
    const detail = (await request(app).get(`/api/spools/${walnut.id}`)).body;
    expect(detail.sources.product.colorHex).toMatchObject({ source: "orca_import", sourceRef: "Sunlu - Walnut Wood.json" });
    expect(detail.imported[0]).toMatchObject({ fileName: "Sunlu - Walnut Wood.json", generatedBy: "spoolman2slicer" });
    expect(detail.imported[0].settings.filament_flow_ratio).toBe("0.94");

    const again = await request(app).post("/api/import/orca").send({ rows }).expect(200);
    expect(again.body.files).toBe(0);
  });

  it("rejects paths outside the filament folder", async () => {
    await request(app)
      .post("/api/import/orca")
      .send({ rows: [{ fileName: "../machine/x.json", vendor: "a", material: "PLA" }] })
      .expect(400);
  });
});
